"""Код позиции меню из её названия — без frappe.

Владельцу бургерной вводить item_code не нужно (в форме раздела «Меню» этого
поля нарочно нет — см. presets/food.json). Код рождается транслитерацией
названия: «Классик бургер» → «KLASSIK-BURGER», «Кола 0,5 л» → «KOLA-0-5-L».
Уникальность (суффикс -2, -3…) — уже с frappe, в habibi_ai/items.py.
"""

import re

_MAP = {
	"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh", "з": "z",
	"и": "i", "й": "i", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
	"с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
	"ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

# Всё, что не латинская буква и не цифра после транслитерации, — разделитель:
# пробелы, запятые, точки и прочая пунктуация схлопываются в один «-»
_SEPARATOR = re.compile(r"[^a-z0-9]+")


def slug(text, max_len=40):
	"""Верхний регистр, кириллица → латиница, разделители → «-», обрезка по длине.

	Обрезка режет по символам, а не по словам: код — читаемый ориентир для
	владельца, а не точный перевод, и хвостовой «-» после неё убираем, чтобы
	не остался висящий разделитель.
	"""
	latin = "".join(_MAP.get(ch, ch) for ch in (text or "").strip().lower())
	code = "-".join(part for part in _SEPARATOR.split(latin) if part).upper()
	return code[:max_len].rstrip("-")
