"""Код позиции меню из её названия — без frappe.

Владельцу бургерной вводить item_code не нужно (в форме раздела «Меню» этого
поля нарочно нет — см. presets/food.json). Код рождается транслитерацией
названия: «Классик бургер» → «KLASSIK-BURGER», «Кола 0,5 л» → «KOLA-0-5-L»,
«Құрт» → «KURT». Уникальность (суффикс -2, -3…) — здесь же, как чистая
функция: сам поиск занятого кода в базе — уже в habibi_ai/items.py.
"""

import re

_MAP = {
	"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh", "з": "z",
	"и": "i", "й": "i", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
	"с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
	"ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
	# Казахские буквы, которых нет в русском алфавите — своя вертикаль
	# может завестись и на казахском сайте, а не только на русском
	"ә": "a", "ғ": "g", "қ": "k", "ң": "n", "ө": "o", "ұ": "u", "ү": "u", "һ": "h", "і": "i",
}

# Всё, что не латинская буква и не цифра после транслитерации, — разделитель:
# пробелы, запятые, точки и прочая пунктуация схлопываются в один «-»
_SEPARATOR = re.compile(r"[^a-z0-9]+")


def slug(text, max_len=40):
	"""Верхний регистр, кириллица → латиница, разделители → «-», обрезка по длине.

	Обрезка режет по символам, а не по словам: код — читаемый ориентир для
	владельца, а не точный перевод, и хвостовой «-» после неё убираем, чтобы
	не остался висящий разделитель. Название без транслитерируемых символов
	(эмодзи, одна пунктуация) даёт пустую строку — запасной код на этот
	случай подставляет вызывающая сторона (habibi_ai/items.py).
	"""
	latin = "".join(_MAP.get(ch, ch) for ch in (text or "").strip().lower())
	code = "-".join(part for part in _SEPARATOR.split(latin) if part).upper()
	return code[:max_len].rstrip("-")


def unique_code(base, exists, max_len=40):
	"""base занят (exists(base) — правда) — суффикс -2, -3…, пока exists не
	ответит «свободно». exists — callable(code) -> bool, чтобы логику подбора
	суффикса можно было проверить без frappe; настоящий поиск в базе — в
	habibi_ai/items.py._unique_code.

	Обрезаем по max_len с учётом длины суффикса и убираем получившийся
	хвостовой «-» перед ним — иначе на границе обрезки получилось бы
	«BASE--2» вместо «BASE-2».
	"""
	if not exists(base):
		return base
	n = 2
	while True:
		suffix = f"-{n}"
		candidate = base[: max_len - len(suffix)].rstrip("-") + suffix
		if not exists(candidate):
			return candidate
		n += 1
