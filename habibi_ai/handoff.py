"""Передача разговора оператору. ЗАГЛУШКА: поток уведомления ещё не выбран.

Сейчас функция только пишет в журнал событие `handoff_requested` — с причиной и
ссылкой на чат. Оператора она не уведомляет и бота на паузу не ставит. Клиенту
при этом уходит честный текст «свяжитесь с оператором», а не обещание, что его
вопрос уже передан.

Зачем заглушка. Страж подменяет ответ бота, когда действие не удалось (например,
заказ не оформился), и человеку об этом нужно узнать. Но КАК именно — не решено,
и выбирать поток за владельца нельзя. Единая точка вызова нужна, чтобы потом
поменять только тело `request_operator`, не трогая ни цикл, ни стража.

Варианты потока (выбрать после того, как в журнале накопится статистика «нужен
оператор» — она видна в `events.guard_stats`, ключ `handoffs`):
- метка «нужен оператор» у чата и уведомление в кабинете (там уже есть realtime);
- сообщение оператору в Telegram с чатом и причиной;
- пауза бота в чате, пока не ответит человек (механизм паузы канала уже есть);
- Notification Log / ToDo ERPNext.
Предварительный выбор: метка и уведомление в кабинете плюс пауза бота.
"""

from habibi_ai import events

EVENT_TYPE = "handoff_requested"


def request_operator(context, reason):
	"""Записывает, что разговору нужен оператор; возвращает имя события или None.

	Заглушка: только журнал (см. докстринг модуля). Запись безопасна для хода —
	`events.record` сама глотает сбои и пробрасывает только дедлок и таймаут.
	"""
	return events.record(
		EVENT_TYPE,
		f"Нужен оператор: {reason}",
		actor="System",
		context=context,
		data={"reason": reason},
	)
